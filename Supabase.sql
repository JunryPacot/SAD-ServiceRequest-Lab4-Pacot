-- LABORATORY 4 - ROLE-BASED ASSET TRANSACTION AND APPROVAL MANAGEMENT
-- Run this in Supabase SQL Editor.

create table if not exists profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default 'User',
  role text not null default 'requester' check (role in ('admin','staff','requester')),
  created_at timestamptz not null default now()
);

create table if not exists equipment (
  id bigint generated by default as identity primary key,
  asset_code text unique not null,
  name text not null,
  category text not null,
  description text,
  status text not null default 'Available'
    check (status in ('Available','Borrowed','Maintenance')),
  created_at timestamptz not null default now()
);

create table if not exists borrowing_requests (
  id bigint generated by default as identity primary key,
  equipment_id bigint not null references equipment(id),
  requester_id uuid not null references auth.users(id),
  requester_name text not null,
  purpose text not null,
  date_requested timestamptz not null default now(),
  expected_return date,
  actual_return date,
  status text not null default 'Pending'
    check (status in ('Pending','Approved','Rejected','Released','Returned','Overdue','Closed')),
  damage_report text,
  approved_by uuid references auth.users(id),
  released_at timestamptz,
  returned_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists maintenance_requests (
  id bigint generated by default as identity primary key,
  equipment_id bigint not null references equipment(id),
  submitted_by uuid not null references auth.users(id),
  description text not null,
  status text not null default 'Pending' check (status in ('Pending','In Progress','Completed')),
  created_at timestamptz not null default now()
);

create table if not exists audit_logs (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id),
  action text not null,
  module text not null,
  record_id bigint,
  description text not null,
  created_at timestamptz not null default now()
);

-- Keep Lab 3 service requests available as the existing system module.
