-- Re-runnable policy cleanup.
do $$
declare p record;
begin
  for p in select schemaname, tablename, policyname from pg_policies
           where schemaname='public' and tablename in ('profiles','equipment','borrowing_requests','maintenance_requests','audit_logs','service_requests')
  loop execute format('drop policy if exists %I on %I.%I', p.policyname, p.schemaname, p.tablename); end loop;
end $$;

create policy profiles_select_own on profiles for select to authenticated using (id = auth.uid() or public.is_admin());
create policy profiles_admin_all on profiles for all to authenticated using (public.is_admin()) with check (public.is_admin());

create policy equipment_view on equipment for select to authenticated using (true);
create policy equipment_admin_insert on equipment for insert to authenticated with check (public.is_admin());
create policy equipment_admin_update on equipment for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy equipment_admin_delete on equipment for delete to authenticated using (public.is_admin());

create policy borrowing_view on borrowing_requests for select to authenticated
using (requester_id = auth.uid() or public.is_staff_or_admin());
create policy borrowing_insert on borrowing_requests for insert to authenticated
with check (requester_id = auth.uid() and status = 'Pending');
create policy borrowing_staff_update on borrowing_requests for update to authenticated
using (public.is_staff_or_admin()) with check (public.is_staff_or_admin());
create policy borrowing_admin_delete on borrowing_requests for delete to authenticated
using (public.is_admin());

create policy maintenance_view on maintenance_requests for select to authenticated
using (submitted_by = auth.uid() or public.is_staff_or_admin());
create policy maintenance_insert on maintenance_requests for insert to authenticated
with check (submitted_by = auth.uid());
create policy maintenance_staff_update on maintenance_requests for update to authenticated
using (public.is_staff_or_admin()) with check (public.is_staff_or_admin());

create policy audit_admin_view on audit_logs for select to authenticated using (public.is_admin());
create policy audit_authenticated_insert on audit_logs for insert to authenticated with check (user_id = auth.uid());

create policy service_view on service_requests for select to authenticated using (true);
create policy service_insert on service_requests for insert to authenticated with check (user_id = auth.uid());
create policy service_update_own on service_requests for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy service_delete_own on service_requests for delete to authenticated using (user_id = auth.uid());

